def solution(n):
    # n칸에 도달하는 방법 수 = (n-1칸 방법 수) + (n-2칸 방법 수). 마지막에 1칸을 뛰었거나 2칸을 뛰었거나 둘 중 하나이기 때문이다. (피보나치 수와 같은 규칙)
    # 시간 복잡도: O(n)
    if n < 3:
        return n
    else:
        a, b = 1, 2
        for _ in range(3, n + 1):
            a, b = b, (a + b) % 1234567  # 수가 너무 커지지 않게 매번 나머지만 남긴다
        return b
